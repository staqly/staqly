"""Generate ``src/staqly/_client_sync.py`` from ``src/staqly/_client_async.py``.

The async client is the source of truth. This strips ``async``/``await``,
drops the ``Async`` prefix from names and swaps the async dunders, so the sync
and async clients always expose an identical surface. Lines ending in
``# async-only`` are removed. Run ``make gen`` (or this script) after editing
the async client; ``tests/test_codegen.py`` fails if the output is stale.

Usage: python scripts/gen_sync.py [--check]
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "staqly" / "_client_async.py"
DST = ROOT / "src" / "staqly" / "_client_sync.py"

HEADER = (
    "# GENERATED by scripts/gen_sync.py from _client_async.py — do not edit by hand.\n"
    "# Run `make gen` after changing the async client.\n"
)

REPLACEMENTS: list[tuple[str, str]] = [
    (r"\basync def\b", "def"),
    (r"\basync for\b", "for"),
    (r"\basync with\b", "with"),
    (r"\bawait\s+", ""),
    (r"__aenter__", "__enter__"),
    (r"__aexit__", "__exit__"),
    (r"\baclose\b", "close"),
    (r"\baiter_(lines|bytes|text|raw)\b", r"iter_\1"),
    (r"\baread\b", "read"),
    (r"cabc\.Awaitable\[(\w+)\]", r"\1"),
    (r"\bAsync([A-Z]\w*)", r"\1"),
]


def generate(source: str) -> str:
    lines = [ln for ln in source.splitlines() if not ln.rstrip().endswith("# async-only")]
    out = "\n".join(lines) + "\n"
    for pattern, repl in REPLACEMENTS:
        out = re.sub(pattern, repl, out)
    out = out.replace(
        '"""Async client and resources — the source of truth.',
        '"""Sync client and resources (generated from the async client).',
        1,
    )
    return _ruff_format(HEADER + out)


def _ruff_format(code: str) -> str:
    """Sorts imports and formats like the rest of the package (shorter lines may re-flow)."""
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "_client_sync.py"
        path.write_text(code, encoding="utf-8")
        config = ["--config", str(ROOT / "pyproject.toml")]
        ruff = [sys.executable, "-m", "ruff"]
        subprocess.run([*ruff, "check", "--quiet", "--select", "I", "--fix", *config, str(path)], check=True)
        subprocess.run([*ruff, "format", "--quiet", *config, str(path)], check=True)
        return path.read_text(encoding="utf-8")


def main() -> int:
    expected = generate(SRC.read_text(encoding="utf-8"))
    if "--check" in sys.argv:
        if DST.read_text(encoding="utf-8") != expected:
            print(f"{DST.name} is stale; run `make gen`", file=sys.stderr)
            return 1
        return 0
    DST.write_text(expected, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
