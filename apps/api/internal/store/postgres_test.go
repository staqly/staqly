// The rewrite from SQLite to PostgreSQL: each rule once, and the placeholder scanner around literals,
// identifiers and comments.
func TestPostgresRewrite(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"SELECT * FROM t WHERE a = ? AND b = ?", "SELECT * FROM t WHERE a = $1 AND b = $2"},
		{"UPDATE t SET a = ?1, b = ?1 WHERE id = ?2", "UPDATE t SET a = $1, b = $1 WHERE id = $2"},
		{"SELECT '?', \"x?\" FROM t -- why?\nWHERE a = ?", "SELECT '?', \"x?\" FROM t -- why?\nWHERE a = $1"},
		{"SELECT 'it''s ?' /* ? */ , ?", "SELECT 'it''s ?' /* ? */ , $1"},
		{"ORDER BY c.name COLLATE NOCASE, id", "ORDER BY lower(c.name), id"},
		{"p.content LIKE ? ESCAPE '\\' COLLATE NOCASE", "p.content ILIKE $1 ESCAPE '\\'"},
		{"WHERE instr(media, ?) > 0", "WHERE strpos(media, $1) > 0"},
		{"NOT (type GLOB 'api_key.*' OR type GLOB 'session.*')", "NOT (starts_with(type, 'api_key.') OR starts_with(type, 'session.'))"},
		{"id IN (SELECT value FROM json_each(?1))", "id IN (SELECT value FROM json_array_elements_text(CAST($1 AS json)))"},
		{"FROM posts, json_each(posts.tags) WHERE", "FROM posts, json_array_elements_text(CAST(posts.tags AS json)) WHERE"},
		{"SELECT CAST(COALESCE(SUM(size_bytes), 0) AS INTEGER) AS used", "SELECT CAST(COALESCE(SUM(size_bytes), 0) AS BIGINT) AS used"},
		{"SUM(status = 'pending' AND attempts = 0)", "SUM(CASE WHEN status = 'pending' AND attempts = 0 THEN 1 ELSE 0 END)"},
		{"SET media = (SELECT json_group_array(j.value) FROM t)", "SET media = (SELECT COALESCE(json_agg(j.value), '[]'::json) FROM t)"},
		{"INSERT OR IGNORE INTO stripe_events (id, created_at) VALUES (?, ?);", "INSERT INTO stripe_events (id, created_at) VALUES ($1, $2) ON CONFLICT DO NOTHING"},
		{"instr(CAST(response_body AS TEXT), CAST(?2 AS TEXT)) > 0", "strpos(convert_from(response_body, 'UTF8'), CAST($2 AS TEXT)) > 0"},
		{"SELECT MAX(version_id) FROM goose_db_version WHERE is_applied = 1", "SELECT MAX(version_id) FROM goose_db_version WHERE is_applied"},
		{"PRAGMA optimize", "SELECT 1"},
		// The job queue's statements (River) are PostgreSQL already: untouched, `?` included (a jsonb operator).
		{"SELECT * FROM river_job WHERE metadata ? 'key' AND id = $1", "SELECT * FROM river_job WHERE metadata ? 'key' AND id = $1"},
	} {
		if got := Postgres(tc.in); got != tc.want {
			t.Errorf("%q\n got  %q\n want %q", tc.in, got, tc.want)
		}
	}
}

func TestPostgresDDL(t *testing.T) {
	in := "CREATE TABLE t (\n-- +sqlite\n    id INTEGER PRIMARY KEY AUTOINCREMENT,\n-- +end\n-- +postgres\n--     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n-- -- @goose StatementBegin\n-- +end\n    b BLOB, j TEXT CHECK (json_valid(j))\n);"
	want := "CREATE TABLE t (\n    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n-- +goose StatementBegin\n    b BYTEA, j TEXT CHECK (j IS JSON)\n);"
	if got := postgresDDL(in); got != want {
		t.Fatalf("postgresDDL:\n%s\nwant:\n%s", got, want)
	}
}

// A database made before the squash (goose at 47, no version 1) opens without re-running 00001_init; one
// stopped part way (45: before the credits and entitlements folded into 00001_init) is refused.
func TestBaselineSquash(t *testing.T) {
	for _, tc := range []struct {
		max  int
		fail bool
	}{{47, false}, {45, true}, {30, true}} {
		path := t.TempDir() + "/old.db"
		raw, err := sql.Open("sqlite", path)
		if err != nil {
			t.Fatal(err)
		}
		// The tables of the squashed schema that later migrations (00048...) change.
		_, err = raw.Exec(`CREATE TABLE goose_db_version (id INTEGER PRIMARY KEY AUTOINCREMENT, version_id INTEGER NOT NULL,
			is_applied INTEGER NOT NULL, tstamp TIMESTAMP DEFAULT (datetime('now')));
			INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, 1), (?, 1);
			CREATE TABLE workspaces (id TEXT PRIMARY KEY, subscription_status TEXT, updated_at TEXT);
			CREATE TABLE webhook_deliveries (workspace_id TEXT, status TEXT, next_attempt_at TEXT);
			CREATE TABLE posts (id TEXT PRIMARY KEY, workspace_id TEXT, status TEXT, publish_at TEXT);
			CREATE TABLE post_targets (channel_id TEXT, status TEXT, published_at TEXT);
			CREATE TABLE post_comments (workspace_id TEXT, parent_id TEXT, preview_id TEXT, created_at TEXT);
			CREATE TABLE email_codes (id TEXT PRIMARY KEY);
			CREATE TABLE channels (id TEXT PRIMARY KEY, provider TEXT);
			CREATE TABLE media_projects (id TEXT PRIMARY KEY)`, tc.max)
		raw.Close()
		if err != nil {
			t.Fatal(err)
		}
		db, err := Open(context.Background(), path)
		if tc.fail {
			if err == nil {
				db.Close()
				t.Fatalf("version %d: opened, want refused", tc.max)
			}
			continue
		}
		if err != nil {
			t.Fatalf("version %d: %v", tc.max, err)
		}
		var n int
		_ = db.QueryRow(`SELECT COUNT(*) FROM goose_db_version WHERE version_id = 1`).Scan(&n)
		db.Close()
		if n != 1 {
			t.Fatalf("version 1 recorded %d times, want 1", n)
		}
	}
}
